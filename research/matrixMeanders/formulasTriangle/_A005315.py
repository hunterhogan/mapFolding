def _crunchCoefficients(次coefficient: int, numerator: tuple[int, ...], stepsNumerator: tuple[int, ...], stepsDenominator: tuple[int, ...]) -> int:
	if 次coefficient < 0:
		message: str = f"I received {次coefficient = }, but the coefficient index must be nonnegative."
		raise ValueError(message)
	coefficients: tuple[int, ...] = (*numerator[0:次coefficient + zeroIndexed], *(0 for _次 in loops(次coefficient + zeroIndexed - len(numerator))))
	coefficients = reduce(_crunchNumerator, stepsNumerator, coefficients)
	# TODO I assume humpy_cytoolz typing is wrong.
	return get(-1, reduce(partial(_crunchDenominator, 次coefficient=次coefficient), stepsDenominator, coefficients))  # pyright: ignore[reportReturnType]

def _crunchNumerator(coefficients: tuple[int, ...], step: int) -> tuple[int, ...]:
	unmodified, minuend = tuple(split_into(coefficients, (min(step, len(coefficients)), None)))
	return (*unmodified, *map(sub, minuend, coefficients[0:-step]))

def _crunchDenominator(coefficients: tuple[int, ...], step: int, *, 次coefficient: int) -> tuple[int, ...]:
	return tuple(take(次coefficient + zeroIndexed, chain.from_iterable(zip_longest(*map(accumulate, distribute(step, coefficients)), fillvalue=0))))

